CREATE OR REPLACE FUNCTION public.refresh_base_map_lod()
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    TRUNCATE TABLE public.base_map_lod;

    WITH levels AS (
        SELECT *
        FROM (VALUES
            (2::SMALLINT, 3::SMALLINT, 8192.0::DOUBLE PRECISION, 32768.0::DOUBLE PRECISION),
            (4::SMALLINT, 5::SMALLINT, 2048.0::DOUBLE PRECISION, 8192.0::DOUBLE PRECISION),
            (6::SMALLINT, 7::SMALLINT, 512.0::DOUBLE PRECISION, 2048.0::DOUBLE PRECISION),
            (8::SMALLINT, 9::SMALLINT, 128.0::DOUBLE PRECISION, 512.0::DOUBLE PRECISION),
            (10::SMALLINT, 11::SMALLINT, 32.0::DOUBLE PRECISION, 128.0::DOUBLE PRECISION),
            (12::SMALLINT, 13::SMALLINT, 8.0::DOUBLE PRECISION, 32.0::DOUBLE PRECISION)
        ) AS value(lod, maximum_zoom, tolerance_m, cell_size_m)
    ),
    generalized AS (
        SELECT
            level.lod,
            feature.theme,
            feature.class,
            feature.min_zoom,
            level.tolerance_m,
            level.cell_size_m,
            ST_SimplifyPreserveTopology(feature.geom_local, level.tolerance_m) AS geom
        FROM public.base_surface_feature feature
        CROSS JOIN levels level
        WHERE feature.min_zoom <= level.maximum_zoom
          AND feature.max_zoom >= level.lod
    ),
    located AS (
        SELECT
            *,
            FLOOR((ST_X(ST_PointOnSurface(geom)) - 12550000.0) / cell_size_m)::INTEGER AS cell_x,
            FLOOR((2800000.0 - ST_Y(ST_PointOnSurface(geom))) / cell_size_m)::INTEGER AS cell_y
        FROM generalized
        WHERE NOT ST_IsEmpty(geom)
    ),
    aggregated AS (
        SELECT
            lod,
            theme,
            class,
            min_zoom,
            cell_x,
            cell_y,
            ST_CollectionExtract(
                ST_MakeValid(
                    ST_UnaryUnion(ST_Collect(geom))
                ),
                3
            )::geometry(Geometry, 3857) AS geom
        FROM located
        GROUP BY lod, theme, class, min_zoom, cell_x, cell_y
    ),
    numbered AS (
        SELECT
            lod,
            theme,
            ROW_NUMBER() OVER (
                PARTITION BY lod, theme
                ORDER BY cell_y, cell_x, min_zoom, class
            )::BIGINT AS render_id,
            class,
            min_zoom,
            geom
        FROM aggregated
        WHERE NOT ST_IsEmpty(geom)
    )
    INSERT INTO public.base_map_lod (
        lod, theme, render_id, source_feature_id, class, name, min_zoom, geom
    )
    SELECT
        lod, theme, render_id, NULL, class, NULL, min_zoom, geom
    FROM numbered;

    INSERT INTO public.base_map_lod (
        lod, theme, render_id, source_feature_id, class, name, min_zoom, geom
    )
    SELECT
        level.lod,
        'boundary',
        ROW_NUMBER() OVER (
            PARTITION BY level.lod
            ORDER BY area.adcode
        )::BIGINT,
        area.adcode::TEXT,
        area.level,
        area.name,
        2,
        ST_SimplifyPreserveTopology(
            ST_Boundary(area.geom_local),
            level.tolerance_m
        )
    FROM public.admin_area area
    CROSS JOIN (VALUES
        (2::SMALLINT, 8192.0::DOUBLE PRECISION),
        (4::SMALLINT, 2048.0::DOUBLE PRECISION),
        (6::SMALLINT, 512.0::DOUBLE PRECISION),
        (8::SMALLINT, 128.0::DOUBLE PRECISION),
        (10::SMALLINT, 32.0::DOUBLE PRECISION),
        (12::SMALLINT, 8.0::DOUBLE PRECISION)
    ) AS level(lod, tolerance_m);

    ANALYZE public.base_map_lod;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_local_basemap_vector_tile(
    p_theme VARCHAR,
    p_z INTEGER,
    p_x INTEGER,
    p_y INTEGER
)
RETURNS BYTEA
LANGUAGE sql
STABLE
PARALLEL SAFE
AS $$
    WITH tile_bounds AS (
        SELECT
            public.local_tile_envelope(p_z, p_x, p_y) AS geom,
            262144.0 / power(2, p_z) AS tile_size
    ),
    selected_lod AS (
        SELECT CASE
            WHEN p_z BETWEEN 2 AND 3 THEN 2
            WHEN p_z BETWEEN 4 AND 5 THEN 4
            WHEN p_z BETWEEN 6 AND 7 THEN 6
            WHEN p_z BETWEEN 8 AND 9 THEN 8
            WHEN p_z BETWEEN 10 AND 11 THEN 10
            WHEN p_z BETWEEN 12 AND 13 THEN 12
            ELSE NULL
        END::SMALLINT AS lod
    ),
    source_feature AS (
        SELECT
            feature.render_id AS id,
            feature.source_feature_id,
            feature.class,
            feature.name,
            feature.geom
        FROM public.base_map_lod feature
        CROSS JOIN selected_lod selected
        CROSS JOIN tile_bounds bounds
        WHERE selected.lod IS NOT NULL
          AND feature.lod = selected.lod
          AND feature.theme = p_theme
          AND feature.min_zoom <= p_z
          AND feature.geom && ST_Expand(bounds.geom, bounds.tile_size * 64.0 / 4096.0)

        UNION ALL

        SELECT
            feature.id,
            feature.source_feature_id,
            feature.class,
            feature.name,
            feature.geom_local
        FROM public.base_surface_feature feature
        CROSS JOIN tile_bounds bounds
        WHERE p_z >= 14
          AND feature.theme = p_theme
          AND p_z BETWEEN feature.min_zoom AND feature.max_zoom
          AND feature.geom_local && ST_Expand(bounds.geom, bounds.tile_size * 64.0 / 4096.0)

        UNION ALL

        SELECT
            area.adcode::BIGINT,
            area.adcode::TEXT,
            area.level,
            area.name,
            ST_Boundary(area.geom_local)
        FROM public.admin_area area
        CROSS JOIN tile_bounds bounds
        WHERE p_theme = 'boundary'
          AND p_z >= 14
          AND area.geom_local && ST_Expand(bounds.geom, bounds.tile_size * 64.0 / 4096.0)
    ),
    tile_feature AS (
        SELECT
            source.id,
            source.source_feature_id,
            source.class,
            source.name,
            ST_AsMVTGeom(source.geom, bounds.geom, 4096, 64, true) AS geom
        FROM source_feature source
        CROSS JOIN tile_bounds bounds
    ),
    valid_feature AS (
        SELECT *
        FROM tile_feature
        WHERE geom IS NOT NULL
          AND NOT ST_IsEmpty(geom)
    )
    SELECT COALESCE(
        ST_AsMVT(valid_feature, p_theme, 4096, 'geom'),
        ''::BYTEA
    )
    FROM valid_feature;
$$;

CREATE OR REPLACE FUNCTION public.get_local_vector_tile(
    p_layer_code VARCHAR,
    p_z INTEGER,
    p_x INTEGER,
    p_y INTEGER
)
RETURNS BYTEA
LANGUAGE plpgsql
STABLE
PARALLEL SAFE
AS $$
DECLARE
    v_tile BYTEA;
BEGIN
    IF p_layer_code IN ('landcover', 'water', 'building', 'boundary', 'parking') THEN
        RETURN public.get_local_basemap_vector_tile(p_layer_code, p_z, p_x, p_y);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM public.map_layer
        WHERE code = p_layer_code AND enabled = true
    ) THEN
        RAISE EXCEPTION 'Map layer does not exist or is disabled: %', p_layer_code;
    END IF;

    WITH tile_bounds AS (
        SELECT
            public.local_tile_envelope(p_z, p_x, p_y) AS geom,
            262144.0 / power(2, p_z) AS tile_size
    ),
    tile_feature AS (
        SELECT
            feature.id,
            feature.source_feature_id,
            feature.name,
            feature.properties,
            ST_AsMVTGeom(
                ST_SetSRID(feature.geom_local, 3857),
                bounds.geom,
                4096,
                64,
                true
            ) AS geom
        FROM public.map_feature feature
        JOIN public.map_layer layer ON layer.id = feature.layer_id
        CROSS JOIN tile_bounds bounds
        WHERE layer.code = p_layer_code
          AND layer.enabled = true
          AND p_z BETWEEN layer.min_zoom AND layer.max_zoom
          AND ST_SetSRID(feature.geom_local, 3857) &&
              ST_Expand(bounds.geom, bounds.tile_size * 64.0 / 4096.0)
    ),
    valid_feature AS (
        SELECT * FROM tile_feature
        WHERE geom IS NOT NULL AND NOT ST_IsEmpty(geom)
    )
    SELECT COALESCE(ST_AsMVT(valid_feature, p_layer_code, 4096, 'geom'), ''::BYTEA)
    INTO v_tile
    FROM valid_feature;

    RETURN v_tile;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_local_base_vector_tile(
    p_z INTEGER,
    p_x INTEGER,
    p_y INTEGER
)
RETURNS BYTEA
LANGUAGE sql
STABLE
PARALLEL SAFE
AS $$
    WITH layer_tile(draw_order, tile) AS (
        VALUES
            (10, public.get_local_basemap_vector_tile('landcover', p_z, p_x, p_y)),
            (20, public.get_local_basemap_vector_tile('water', p_z, p_x, p_y)),
            (30, public.get_local_basemap_vector_tile('building', p_z, p_x, p_y)),
            (35, public.get_local_basemap_vector_tile('parking', p_z, p_x, p_y)),
            (40, public.get_local_basemap_vector_tile('boundary', p_z, p_x, p_y)),
            (50, public.get_local_road_vector_tile(p_z, p_x, p_y))
    )
    SELECT COALESCE(
        string_agg(tile, ''::BYTEA ORDER BY draw_order)
            FILTER (WHERE octet_length(tile) > 0),
        ''::BYTEA
    )
    FROM layer_tile;
$$;

