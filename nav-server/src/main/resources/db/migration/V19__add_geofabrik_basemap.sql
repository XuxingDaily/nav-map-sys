CREATE TABLE public.base_surface_feature (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    theme               VARCHAR(20) NOT NULL,
    source_layer        VARCHAR(80) NOT NULL,
    source_feature_id   VARCHAR(100),
    class               VARCHAR(50) NOT NULL,
    code                INTEGER,
    name                TEXT,
    min_zoom            SMALLINT NOT NULL,
    max_zoom            SMALLINT NOT NULL DEFAULT 22,
    geom                geometry(MultiPolygon, 4326) NOT NULL,
    geom_local          geometry(MultiPolygon, 3857)
        GENERATED ALWAYS AS (ST_Transform(geom, 3857)) STORED,
    area_m2             DOUBLE PRECISION
        GENERATED ALWAYS AS (ST_Area(ST_Transform(geom, 3857))) STORED,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT base_surface_feature_theme_ck
        CHECK (theme IN ('landcover', 'water', 'building', 'parking')),
    CONSTRAINT base_surface_feature_zoom_ck
        CHECK (min_zoom BETWEEN 0 AND 22 AND max_zoom BETWEEN min_zoom AND 22),
    CONSTRAINT base_surface_feature_geom_ck
        CHECK (NOT ST_IsEmpty(geom) AND ST_IsValid(geom))
);

CREATE INDEX base_surface_feature_theme_zoom_idx
    ON public.base_surface_feature (theme, min_zoom, max_zoom);
CREATE INDEX base_surface_feature_class_idx
    ON public.base_surface_feature (theme, class);
CREATE INDEX base_surface_feature_geom_local_gix
    ON public.base_surface_feature USING GIST (geom_local);

CREATE TABLE public.admin_area (
    adcode          INTEGER PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    level           VARCHAR(30) NOT NULL,
    parent_adcode   INTEGER,
    properties      JSONB NOT NULL DEFAULT '{}'::JSONB,
    geom            geometry(MultiPolygon, 4326) NOT NULL,
    geom_local      geometry(MultiPolygon, 3857)
        GENERATED ALWAYS AS (ST_Transform(geom, 3857)) STORED,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT admin_area_geom_ck
        CHECK (NOT ST_IsEmpty(geom) AND ST_IsValid(geom))
);

CREATE INDEX admin_area_geom_local_gix
    ON public.admin_area USING GIST (geom_local);

-- One shared offline render table is deliberately used for every basemap
-- theme. Theme-specific physical tables would add schema complexity without
-- improving the spatial lookup pattern at Guangzhou scale.
CREATE TABLE public.base_map_lod (
    lod                 SMALLINT NOT NULL,
    theme               VARCHAR(20) NOT NULL,
    render_id           BIGINT NOT NULL,
    source_feature_id   VARCHAR(100),
    class               VARCHAR(50) NOT NULL,
    name                TEXT,
    min_zoom            SMALLINT NOT NULL,
    geom                geometry(Geometry, 3857) NOT NULL,

    PRIMARY KEY (lod, theme, render_id),
    CONSTRAINT base_map_lod_level_ck CHECK (lod IN (2, 4, 6, 8, 10, 12)),
    CONSTRAINT base_map_lod_theme_ck
        CHECK (theme IN ('landcover', 'water', 'building', 'parking', 'boundary')),
    CONSTRAINT base_map_lod_geom_ck CHECK (NOT ST_IsEmpty(geom))
);

CREATE INDEX base_map_lod_lookup_idx
    ON public.base_map_lod (theme, lod, min_zoom);
CREATE INDEX base_map_lod_geom_gix
    ON public.base_map_lod USING GIST (geom);

